export function PixelSprite({
  name,
  size = 32,
  color,
  label,
}: {
  name: SpriteName;
  size?: number;
  color?: string;
  label?: string;
}) {
  const pixels = PIXELS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill={color ?? "currentColor"}
      role={label ? "img" : "presentation"}
      aria-label={label}
      shapeRendering="crispEdges"
      style={{ display: "block" }}
    >
      {pixels.map(([x, y], i) => (
        <rect key={i} x={x} y={y} width={1} height={1} />
      ))}
    </svg>
  );
}

